// Client-side copies of the Mark component's glyphs (src/components/Mark.astro).
const glyph: Record<string, string> = {
	register: '<circle cx="8" cy="8" r="4.25"/><path d="M8 1v14M1 8h14"/>',
	off: '<circle cx="6.5" cy="6.5" r="4"/><circle cx="9.5" cy="9.5" r="4" stroke-dasharray="2 1.5"/>',
	upstream: '<circle cx="8" cy="8" r="4.25" stroke-dasharray="2.2 1.6"/><path d="M8 1v4.5M8 11v4M1 8h4.5M11 8h4"/>',
	pending: '<circle cx="8" cy="8" r="4.25" stroke-dasharray="1 2"/>',
};

export type MarkKind = 'register' | 'off' | 'upstream' | 'pending';

export function markHTML(kind: MarkKind, label: string) {
	return `<span class="mark is-${kind}" data-mark="${kind}"><svg viewBox="0 0 16 16" aria-hidden="true" fill="none" stroke="currentColor" stroke-width="1.25">${glyph[kind]}</svg><span>${escapeHTML(label)}</span></span>`;
}

export function escapeHTML(s: string) {
	return s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);
}

/** gv-diff's normalisation: drop every line that starts with the generator comment. */
export function normalise(text: string) {
	return text
		.split(/(?<=\n)/)
		.filter((l) => !l.startsWith('<!-- Generated by '))
		.join('');
}

export function generatorLines(text: string) {
	return text.split('\n').filter((l) => l.startsWith('<!-- Generated by '));
}
