/// `p(w) - 1`, without its constant term `1`, divided by `w` (Remez, degree 5 on
/// `[-0x1p-10, 0x1.33a3c38cf408p-7]`).
const PCOEF: [f64; 5] = [
    f64::from_bits(0x3FD5_5555_5555_566F),  //  0x1.555555555566fp-2
    -f64::from_bits(0x3FBC_71C7_1C5D_0CF7), // -0x1.c71c71c5d0cf7p-4
    f64::from_bits(0x3FAF_9ADC_9C26_062D),  //  0x1.f9adc9c26062dp-5
    -f64::from_bits(0x3FA5_113A_CF1A_9A61), // -0x1.5113acf1a9a61p-5
    f64::from_bits(0x3F9E_4DE2_867D_AF6F),  //  0x1.e4de2867daf6fp-6
];

pub fn cbrt(x: f64) -> f64 {
    let u = x.to_bits();
    let sign = u & 0x8000_0000_0000_0000;
    let exponent = ((u >> 52) & 0x7ff) as u32;
    let fraction = u & 0x000f_ffff_ffff_ffff;
    if exponent == 0x7ff {
        return x; // inf, -inf, NaN
    }
    if exponent == 0 {
        if fraction == 0 {
            return x; // ±0
        }
        // Subnormal: 2 + x * 2^1074 * 2^-51 - 2 = x * 2^1023 exactly; cbrt(2^1023) = 2^341.
        let normalized = f64::from_bits(0x4000_0000_0000_0000 | fraction) - 2.0;
        return f64::from_bits(sign | 0x2aa0_0000_0000_0000) * cbrt(normalized);
    }
    // e / 3 and e % 3 by multiplication, as the C does (32-bit wrapping arithmetic).
    let expdiv3 = exponent.wrapping_mul(0x000a_aaab) >> 21;
    let expmod3 = 3 & (exponent.wrapping_mul(0x002a_aaab) >> 21);
    let y = f64::from_bits((u64::from(expmod3 + 0x3ff) << 52) | fraction);
    let scale = f64::from_bits(sign | (u64::from(expdiv3 + 0x2aa) << 52));

    let c = f64::from(CBRT_TABLE[((expmod3 << 7) | (fraction >> 45) as u32) as usize]) / 65536.0;
    let z = c * c * c;
    let zinv = 1.0 / z;
    let w = (y - z) * zinv;
    let pw = w.mul_add(
        w.mul_add(w.mul_add(w.mul_add(PCOEF[4], PCOEF[3]), PCOEF[2]), PCOEF[1]),
        PCOEF[0],
    );
    scale * (c * w).mul_add(pw, c)
}
