fn bits(v: f64) -> String {
    if v.is_nan() {
        format!("{}nan", if v.is_sign_negative() { '-' } else { '+' })
    } else {
        format!("{:016x}", v.to_bits())
    }
}

#[test]
fn strtod_matches_the_c_library() {
    for &(s, want, len, count, scan_len, want_f) in STRTOD {
        let (v, n) = strtod(s);
        assert_eq!((bits(v).as_str(), n), (want, len), "strtod({s:?})");
        assert_eq!(atof(s).to_bits(), v.to_bits(), "atof({s:?})");
        let lf = scan_lf(s);
        assert_eq!(
            lf.map_or(0, |_| 1),
            count.max(0),
            "sscanf({s:?}, \"%lf\") count"
        );
        if let Some((w, rest)) = lf {
            assert_eq!(s.len() - rest.len(), scan_len, "sscanf({s:?}, \"%lf%n\")");
            assert_eq!(bits(w), want, "sscanf({s:?}, \"%lf\") value");
        }
        let one = sscanf(s, "%lf");
        assert_eq!(one.count, count, "sscanf({s:?}, \"%lf\")");
        let f = scan_f(s).map_or("-".to_string(), |(f, _)| {
            if f.is_nan() {
                format!("{}nan", if f.is_sign_negative() { '-' } else { '+' })
            } else {
                format!("{:08x}", f.to_bits())
            }
        });
        assert_eq!(f, want_f, "sscanf({s:?}, \"%f\")");
    }
}

#[test]
fn long_inputs_match_the_c_library() {
    let cases = [
        (format!("1{}", "0".repeat(400)), "7ff0000000000000", 401),
        (format!("0.{}1", "0".repeat(400)), "0000000000000000", 403),
        (format!("{}e-50", "9".repeat(50)), "3ff0000000000000", 54),
        (format!("1.{}1", "0".repeat(800)), "3ff0000000000000", 803),
        (format!("nan({})", "1".repeat(30)), "+nan", 35),
    ];
    for (s, want, len) in cases {
        let (v, n) = strtod(&s);
        assert_eq!((bits(v).as_str(), n), (want, len), "strtod({s:?})");
    }
}

#[test]
fn sscanf_matches_the_c_library() {
    for &(s, fmt, count, values, c, n) in SSCANF {
        let r = sscanf(s, fmt);
        assert_eq!(r.count, count, "sscanf({s:?}, {fmt:?}) count");
        let got: Vec<String> = r.values[..values.len()].iter().map(|&v| bits(v)).collect();
        assert_eq!(got, values, "sscanf({s:?}, {fmt:?}) values");
        assert_eq!(r.c.map_or(-1, i32::from), c, "sscanf({s:?}, {fmt:?}) %c");
        if n >= 0 {
            assert_eq!(
                s.len() - r.rest.len(),
                n as usize,
                "sscanf({s:?}, {fmt:?}%n)"
            );
        }
    }
}

/// `%[^…]`, as `init_job_viewport` (`lib/common/emit.c`) uses it, against the C library:
/// `(input, count and string of "%lf,%lf,%lf,'%[^']'", count, string and %c of
/// "%lf,%lf,%lf,%[^,]%c")`.
#[test]
fn sscanf_scansets_match_the_c_library() {
    let cases = [
        ("1,2,3,'ab c'", 4, Some("ab c"), 4, Some("'ab c'"), None),
        ("1,2,3,'ab", 4, Some("ab"), 4, Some("'ab"), None),
        ("1,2,3,ab", 3, None, 4, Some("ab"), None),
        ("1,2,3,ab,", 3, None, 5, Some("ab"), Some(b',')),
        ("1,2,3,,x", 3, None, 3, None, None),
        ("1,2,3,", 3, None, 3, None, None),
        ("1,2,3", 3, None, 3, None, None),
    ];
    for (s, n1, s1, n2, s2, c2) in cases {
        let r = sscanf(s, "%lf,%lf,%lf,'%[^']'");
        assert_eq!(
            (r.count, r.set, &r.values[..3]),
            (n1, s1, &[1.0, 2.0, 3.0][..]),
            "{s:?}"
        );
        let r = sscanf(s, "%lf,%lf,%lf,%[^,]%c");
        assert_eq!((r.count, r.set, r.c), (n2, s2, c2), "{s:?}");
    }
}
