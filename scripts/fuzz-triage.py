#!/usr/bin/env python3
"""Re-check fuzz cases against the current port, with a stronger C-stability test.

For each case: run C `dot` N times (default 8), the release port once and the debug
port once, and record how many distinct C outputs there were, whether C crashed on any
run, whether the port matches one of C's outputs, the exit statuses and the first
differing line. One JSON object per case on stdout.

  python3 -I scripts/fuzz-triage.py [-n 8] [--fmt svg] CASE.gv... > recheck.jsonl

Uses the same binaries and GVBINDIR as scripts/fuzz-run.py. Files are passed as
arguments (never on stdin).
"""
import argparse
import concurrent.futures as cf
import hashlib
import json
import os
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
GVBINDIR = os.environ.get("GVBINDIR", str(pathlib.Path.home() / "src/gv-ref/lutplugins"))
C_BIN = os.environ.get("C_DOT", "dot")
REL = os.environ.get("PORT_BIN", str(ROOT / "target/release/graphviz-pure"))
DBG = os.environ.get("PORT_DEBUG_BIN", str(ROOT / "target/debug/graphviz-pure"))
TIMEOUT = float(os.environ.get("FUZZ_TIMEOUT", "30"))


def normalize(out):
    return b"".join(l for l in out.splitlines(keepends=True) if not l.startswith(b"<!-- Generated by "))


def run(cmd, path, fmt, env=None, timeout=TIMEOUT):
    try:
        p = subprocess.run(cmd + [f"-T{fmt}", str(path)], capture_output=True, timeout=timeout,
                           env=env, stdin=subprocess.DEVNULL)
    except subprocess.TimeoutExpired:
        return "timeout", b"", b""
    return p.returncode, normalize(p.stdout), p.stderr


def first_diff(a, b):
    al, bl = a.splitlines(), b.splitlines()
    for i, (x, y) in enumerate(zip(al, bl)):
        if x != y:
            return i + 1, x.decode("utf-8", "replace")[:160], y.decode("utf-8", "replace")[:160]
    n = min(len(al), len(bl))
    return n + 1, "<eof>" if len(al) == n else al[n].decode("utf-8", "replace")[:160], "<eof>" if len(bl) == n else bl[n].decode("utf-8", "replace")[:160]


def h(b):
    return hashlib.sha1(b).hexdigest()[:10]


def one(path, n, fmt):
    env = dict(os.environ, GVBINDIR=GVBINDIR)
    cs = [run([C_BIN], path, fmt, env=env) for _ in range(n)]
    rel = run([REL], path, fmt, timeout=TIMEOUT * 2)
    dbg = run([DBG], path, fmt, timeout=TIMEOUT * 4)
    c_ok = [c for c in cs if c[0] != "timeout" and c[0] >= 0]
    variants = sorted({h(c[1]) for c in c_ok})
    rec = {
        "case": str(path),
        "c_runs": n,
        "c_crashes": sum(1 for c in cs if c[0] != "timeout" and c[0] < 0),
        "c_timeouts": sum(1 for c in cs if c[0] == "timeout"),
        "c_variants": len(variants),
        "c_status": sorted({c[0] for c in c_ok}),
        "port_status": rel[0],
        "port_panic": b"panicked at" in rel[2] or rel[0] == 101,
        "debug_panic": b"panicked at" in dbg[2] or dbg[0] == 101,
        "debug_differs": dbg[1] != rel[1],
        "port_matches_some_c": any(c[1] == rel[1] and (c[0] != 0) == (rel[0] != 0) for c in c_ok),
        "port_hash": h(rel[1]),
        "c_hashes": variants,
    }
    if c_ok:
        rec["first_diff"] = first_diff(c_ok[0][1], rel[1])
    if rec["port_panic"]:
        rec["panic"] = rel[2].decode("utf-8", "replace")[-300:]
    if rec["c_crashes"]:
        rec["c_signals"] = sorted({-c[0] for c in cs if c[0] != "timeout" and c[0] < 0})
    return rec


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("files", nargs="+")
    ap.add_argument("-n", type=int, default=8)
    ap.add_argument("--fmt", default="svg")
    ap.add_argument("--jobs", type=int, default=max(1, (os.cpu_count() or 4) - 2))
    a = ap.parse_args()
    with cf.ThreadPoolExecutor(a.jobs) as ex:
        for rec in ex.map(lambda f: one(pathlib.Path(f), a.n, a.fmt), a.files):
            print(json.dumps(rec), flush=True)


if __name__ == "__main__":
    main()
