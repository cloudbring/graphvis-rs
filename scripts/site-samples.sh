#!/usr/bin/env bash
# Builds the site's C-versus-Rust gallery: for each curated input, runs the C reference
# (Graphviz 16.1.0 with only its core, dot and neato plugins, so no Pango) and the port, and writes
#
#   site/public/samples/<name>/{input.gv,c.svg,rust.svg}
#   site/src/data/samples.json
#
# Needs the C oracle, so it runs locally, not in CI; commit what it writes.
#
#   scripts/site-samples.sh
#
# Environment:
#   GVBINDIR  pango-free C plugin dir   (default ~/src/gv-ref/lutplugins)
#   GV_SRC    Graphviz 16.1.0 sources   (default ~/src/gv-ref/graphviz-16.1.0)
#   C_DOT     C dot binary              (default dot)
#
# rust.svg is the native build's output (Apple math on macOS, as the corpus runs).
# The portable-math build (Linux and the browser's WASM) is run too, and its result is
# recorded as identical_portable, because the site's live check runs the WASM build.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
export GVBINDIR="${GVBINDIR:-$HOME/src/gv-ref/lutplugins}"
GV_SRC="${GV_SRC:-$HOME/src/gv-ref/graphviz-16.1.0}"
C_DOT="${C_DOT:-dot}"
OUT="site/public/samples"
DATA="site/src/data/samples.json"

"$C_DOT" -V 2>&1 | grep -q 'version 16.1.0' || { echo "need C Graphviz 16.1.0 as $C_DOT" >&2; exit 1; }
cargo build --release -p graphviz-pure-cli --bin graphviz-pure
cargo build --release -p graphviz-pure-cli --bin graphviz-pure --features graphviz-pure-core/portable-math --target-dir target/portable
RUST="target/release/graphviz-pure"
PORTABLE="target/portable/release/graphviz-pure"

# name | engine | extra flags | source (gv: = Graphviz source tree) | title | features (comma list)
SAMPLES=$(cat <<'EOF'
fsm|dot||gv:graphs/directed/fsm.gv|Finite-state machine|rankdir=LR,edge labels,doublecircle
clust4|dot||gv:graphs/directed/clust4.gv|Clusters|clusters,filled styles
unix|dot||gv:graphs/directed/unix.gv|Unix family tree|hierarchy,41 nodes
structs|dot||gv:graphs/directed/structs.gv|Record ports|records,ports
html-tables|dot||tests/fixtures/html2.gv|HTML-like tables|HTML labels,ports,fonts
ortho-clusters|dot|-Gsplines=ortho|gv:graphs/directed/clust4.gv|Orthogonal routing in clusters|splines=ortho,clusters
ortho-switch|dot|-Gsplines=ortho|gv:graphs/directed/switch.gv|Orthogonal switch network|splines=ortho
concentrate|dot|-Gconcentrate=true|gv:graphs/directed/unix.gv|Concentrated edges|concentrate=true
polyline|dot|-Gsplines=polyline|gv:graphs/directed/abstract.gv|Polyline edges|splines=polyline
curved|dot|-Gsplines=curved|gv:graphs/directed/fsm.gv|Curved edges|splines=curved,edge labels
arrows|dot||gv:graphs/directed/arrows.gv|Every arrowhead|arrowhead,arrowtail,dir
crazy|dot||gv:graphs/directed/crazy.gv|Colours and fonts|colours,fontname,styles
gradients|dot||tests/wild/gv16_graphs_grdradial_f61057.gv|Radial gradients|radialgradient,HTML labels
xlabels|dot||tests/wild/gv16_graphs_xlabels_e9f1cf.gv|External labels|xlabel,forcelabels
compound|dot||tests/wild/gv16_graphs_compound_7ed9c4.gv|Edges between clusters|compound,lhead,ltail
shapes|dot||tests/fixtures/shapes.gv|Node shapes|shapes,polygon
japanese|dot||gv:graphs/directed/japanese.gv|UTF-8 labels|UTF-8,charset
heawood|neato||gv:graphs/undirected/Heawood.gv|Heawood graph|stress majorization
process|neato||gv:graphs/undirected/process.gv|Process graph|stress majorization,undirected
fdp-clusters|fdp||tests/wild/gv16_graphs_fdp_8f3263.gv|fdp with clusters|clusters,force-directed
fdp-clust4|fdp||tests/fixtures/clust4.gv|fdp on nested clusters|clusters
sfdp-smoothing|sfdp||tests/sfdp/attr_smoothing_spring.gv|sfdp spring smoothing|smoothing=spring,multilevel
sfdp-switch|sfdp||tests/sfdp/wild_gv16_directed_switch_2841f8.gv|sfdp switch network|multilevel,quadtree
sfdp-unix|sfdp||gv:graphs/directed/unix.gv|sfdp Unix tree|multilevel,portable-math difference
circo-heawood|circo||gv:graphs/undirected/Heawood.gv|Circular Heawood|biconnected blocks
circo-fsm|circo||gv:graphs/directed/fsm.gv|Circular state machine|edge labels,self-loops
twopi-unix|twopi||gv:graphs/directed/unix.gv|Radial Unix tree|root,radial
osage|osage||tests/wild/gallery_osage_0_f6bd9e.gv|osage cluster packing|clusters,pack
patchwork|patchwork||tests/wild/gallery_patchwork_0_7dbf8c.gv|patchwork treemap|area,clusters
patchwork-unix|patchwork||tests/fixtures/unix.gv|Unix tree as treemap|treemap
EOF
)

strip() { grep -v '^<!-- Generated by ' "$1" || true; }

rm -rf "$OUT"
mkdir -p "$OUT" "$(dirname "$DATA")"
TSV="$(mktemp)"
trap 'rm -f "$TSV"' EXIT
while IFS='|' read -r name engine flags src title features; do
  [ -n "$name" ] || continue
  case "$src" in
    gv:*) path="$GV_SRC/${src#gv:}"; shown="graphviz-16.1.0/${src#gv:}" ;;
    *) path="$src"; shown="$src" ;;
  esac
  d="$OUT/$name"
  mkdir -p "$d"
  cp "$path" "$d/input.gv"
  # Files are passed as arguments (never stdin), as the corpus checks do.
  # shellcheck disable=SC2086
  perl -e 'alarm 60; exec @ARGV' "$C_DOT" "-K$engine" $flags -Tsvg "$d/input.gv" > "$d/c.svg" 2>/dev/null </dev/null || true
  # shellcheck disable=SC2086
  "$RUST" "-K$engine" $flags -Tsvg "$d/input.gv" > "$d/rust.svg" 2>/dev/null </dev/null || true
  # shellcheck disable=SC2086
  "$PORTABLE" "-K$engine" $flags -Tsvg "$d/input.gv" > "$d/.portable.svg" 2>/dev/null </dev/null || true
  same=false; same_p=false
  cmp -s <(strip "$d/c.svg") <(strip "$d/rust.svg") && same=true
  cmp -s <(strip "$d/c.svg") <(strip "$d/.portable.svg") && same_p=true
  rm -f "$d/.portable.svg"
  if [ -n "$flags" ]; then
    # The WASM API takes no -G flags, so the live check renders a copy with the attributes
    # written at the top of the root graph. Only kept if C gives the same bytes for it.
    attrs=$(printf '%s' "$flags" | sed -E 's/-G([^ ]+)/\1;/g')
    perl -0pe "s/\\{/{ $attrs/" "$d/input.gv" > "$d/input.wasm.gv"
    perl -e 'alarm 60; exec @ARGV' "$C_DOT" "-K$engine" -Tsvg "$d/input.wasm.gv" 2>/dev/null </dev/null \
      | cmp -s <(strip "$d/c.svg") <(grep -v '^<!-- Generated by ' || true) \
      || { echo "$name: C output changes when $flags is written into the graph" >&2; exit 1; }
  fi
  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$name" "$engine" "$flags" "$shown" "$title" "$features" "$same" "$same_p" >> "$TSV"
  printf '%-16s %-9s apple=%-5s portable=%s\n' "$name" "$engine" "$same" "$same_p"
done <<< "$SAMPLES"

python3 -I - "$TSV" "$OUT" "$DATA" <<'PY'
import hashlib, json, sys
from pathlib import Path
tsv, out, data = sys.argv[1], Path(sys.argv[2]), Path(sys.argv[3])
items = []
for line in open(tsv, encoding="utf-8"):
    name, engine, flags, src, title, features, same, same_p = line.rstrip("\n").split("\t")
    d = out / name
    sha = lambda f: hashlib.sha256((d / f).read_bytes()).hexdigest()
    items.append({
        "name": name, "title": title, "engine": engine,
        "flags": flags.split() if flags else [],
        "source": src, "features": [f for f in features.split(",") if f],
        "identical": same == "true", "identical_portable": same_p == "true",
        "wasm_input": "input.wasm.gv" if (d / "input.wasm.gv").exists() else "input.gv",
        "sha256": {"c": sha("c.svg"), "rust": sha("rust.svg")},
        "bytes": {f.split(".")[0]: (d / f).stat().st_size for f in ("input.gv", "c.svg", "rust.svg")},
    })
data.write_text(json.dumps(items, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
total = sum(sum(i["bytes"].values()) for i in items)
print(f"wrote {data}: {len(items)} samples, {total/1024:.0f} KiB of files")
PY
