#!/usr/bin/env python3
"""Generate crates/graphviz-pure-core/src/color_table.rs from the Graphviz color sources.

Usage: scripts/gen_color_table.py [GRAPHVIZ_SRC] [OUTPUT]

GRAPHVIZ_SRC defaults to ~/src/gv-ref/graphviz-16.1.0. The three inputs are
lib/common/{brewer_colors,svgcolor_names,color_names}, the same files that
lib/common/make_colortbl.py turns into colortbl.h.
"""

import os
import re
import sys

ENTRY = re.compile(r"^(\S+) (\d+) (\d+) (\d+) (\d+)\s*$")


def main(argv):
    src = os.path.expanduser(argv[1] if len(argv) > 1 else "~/src/gv-ref/graphviz-16.1.0")
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out_path = argv[2] if len(argv) > 2 else os.path.join(root, "crates/graphviz-pure-core/src/color_table.rs")

    entries = {}
    for name in ("brewer_colors", "svgcolor_names", "color_names"):
        with open(os.path.join(src, "lib/common", name), encoding="utf-8") as f:
            for line in f:
                if not line.strip() or line.lstrip().startswith("#"):
                    continue
                m = ENTRY.match(line)
                assert m, f"unexpected entry in {name}: {line!r}"
                key = m.group(1).lower()
                entries[key] = tuple(int(m.group(i)) for i in range(2, 6))

    lines = [
        "//! Color name table generated by `scripts/gen_color_table.py` from",
        "//! `lib/common/{brewer_colors,svgcolor_names,color_names}`. Do not edit by hand.",
        "",
        "/// `(lowercase name, [r, g, b, a])`, sorted by name in byte order for binary search.",
        "pub(crate) static COLOR_LIB: &[(&str, [u8; 4])] = &[",
    ]
    for key in sorted(entries):
        r, g, b, a = entries[key]
        lines.append(f'    ("{key}", [{r}, {g}, {b}, {a}]),')
    lines.append("];")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {len(entries)} colors to {out_path}")


if __name__ == "__main__":
    main(sys.argv)
