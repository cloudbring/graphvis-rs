#!/usr/bin/env node
// WASM end-to-end check: renders every corpus input with the wasm build and compares the
// normalized SVG hash with C Graphviz's (tests/golden/e2e.json), like `gv-diff e2e` does
// for the native build. No npm packages are needed.
//
// Build the package first (see docs/porting/libm.md):
//   cargo build --release --target wasm32-unknown-unknown -p gv-wasm
//   wasm-bindgen --target nodejs --out-dir /tmp/gvwasm/pkg \
//     target/wasm32-unknown-unknown/release/gv_wasm.wasm
// then run from the repository root:
//   node scripts/wasm-e2e.mjs [--pkg /tmp/gvwasm/pkg] [--filter SUBSTR] [--list]
//
// Exits non-zero when a file in tests/golden/e2e-baseline.json (the files the native build
// matches) does not match under wasm.

import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';

const args = process.argv.slice(2);
let pkg = '/tmp/gvwasm/pkg';
let filter = null;
let list = false;
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--pkg') pkg = args[++i];
  else if (args[i] === '--filter') filter = args[++i];
  else if (args[i] === '--list') list = true;
  else {
    console.error(`unknown argument ${args[i]}`);
    process.exit(2);
  }
}
const require = createRequire(import.meta.url);
const gv = require(path.resolve(pkg, 'gv_wasm.js'));

const root = process.cwd();
const golden = JSON.parse(fs.readFileSync(path.join(root, 'tests/golden/e2e.json'), 'utf8')).files;
const baseline = new Set(
  JSON.parse(fs.readFileSync(path.join(root, 'tests/golden/e2e-baseline.json'), 'utf8')).identical,
);
// Same table as crates/gv-diff/src/e2e.rs.
const corpora = {
  main: ['tests/wild', 'tests/fixtures'],
  neato: ['tests/neato'],
  sfdp: ['tests/sfdp'],
  circo: ['tests/circo'],
  twopi: ['tests/twopi'],
  fdp: ['tests/fdp'],
  osage: ['tests/osage'],
  patchwork: ['tests/patchwork'],
  render: ['tests/render'],
};

// Drops the generator comment, which names the program and version.
function normalize(s) {
  return s
    .split(/(?<=\n)/)
    .filter((l) => !l.startsWith('<!-- Generated by '))
    .join('');
}
// FNV-1a, 64-bit.
function fnv(s) {
  let h = 0xcbf29ce484222325n;
  for (const x of Buffer.from(s, 'utf8')) {
    h ^= BigInt(x);
    h = (h * 0x100000001b3n) & 0xffffffffffffffffn;
  }
  return h.toString(16).padStart(16, '0');
}
function renderAll(src) {
  // `renderAll` renders every graph in the file, as `gv-diff e2e` does.
  if (gv.renderAll) return gv.renderAll(src, 'dot', 'svg').join('');
  return gv.render(src, 'dot', 'svg');
}

const t0 = Date.now();
const per = {};
const bad = [];
let regressions = 0;
for (const [c, dirs] of Object.entries(corpora)) {
  const r = (per[c] = { total: 0, identical: 0, differ: 0, error: 0, nativeIdentical: 0 });
  for (const d of dirs) {
    const dir = path.join(root, d);
    if (!fs.existsSync(dir)) continue;
    for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.gv')).sort()) {
      const key = `${c}/${f.slice(0, -3)}`;
      if (!golden[key] || (filter && !key.includes(filter))) continue;
      r.total++;
      if (baseline.has(key)) r.nativeIdentical++;
      const src = fs.readFileSync(path.join(dir, f), 'utf8');
      let out;
      try {
        out = renderAll(src);
      } catch (e) {
        r.error++;
        bad.push(`${key} ERROR ${String(e).slice(0, 80)}`);
        if (baseline.has(key)) regressions++;
        continue;
      }
      if (fnv(normalize(out)) === golden[key]) r.identical++;
      else {
        r.differ++;
        bad.push(key);
        if (baseline.has(key)) regressions++;
      }
    }
  }
}
console.log('corpus     total  wasm-identical  native-identical  differ  error');
const sum = { total: 0, identical: 0, nativeIdentical: 0, differ: 0, error: 0 };
for (const [c, r] of Object.entries(per)) {
  if (!r.total) continue;
  for (const k of Object.keys(sum)) sum[k] += r[k];
  console.log(
    `${c.padEnd(10)} ${String(r.total).padStart(5)}  ${String(r.identical).padStart(14)}  ${String(r.nativeIdentical).padStart(16)}  ${String(r.differ).padStart(6)}  ${String(r.error).padStart(5)}`,
  );
}
console.log(
  `${'all'.padEnd(10)} ${String(sum.total).padStart(5)}  ${String(sum.identical).padStart(14)}  ${String(sum.nativeIdentical).padStart(16)}  ${String(sum.differ).padStart(6)}  ${String(sum.error).padStart(5)}`,
);
console.log(`${((Date.now() - t0) / 1000).toFixed(1)}s; ${regressions} native-identical file(s) differ under wasm`);
if (list) console.log(bad.join('\n'));
process.exit(regressions ? 1 : 0);
